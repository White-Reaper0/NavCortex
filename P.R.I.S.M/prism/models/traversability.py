def _synth_inputs(h: int = PROC_H, w: int = PROC_W, seed: int = 0):
    """Synthetic stand-ins with the right shapes/dtypes, used before the real caches exist."""
    rng = np.random.default_rng(seed)
    rgb = rng.integers(0, 255, (h, w, 3), dtype=np.uint8)
    yy = np.linspace(0, 1, h, dtype=np.float32)[:, None] * np.ones((1, w), np.float32)
    depth = (0.4 + 6.0 * (1.0 - yy)).astype(np.float32)
    valid = np.ones((h, w), bool)
    valid[:int(0.30 * h)] = False
    height = (rng.normal(0, 0.01, (h, w)).astype(np.float32))
    height[:, int(0.7 * w):] += 0.09
    slope = np.abs(rng.normal(4, 2, (h, w))).astype(np.float32)
    rough = np.abs(rng.normal(0.006, 0.003, (h, w))).astype(np.float32)
    lab = np.ones((h, w), np.uint8)
    lab[:int(0.30 * h)] = 0
    lab[:, int(0.7 * w):] = 4
    pmax = np.full((h, w), 0.8, np.float32)
    ent = np.full((h, w), 0.2, np.float32)
    return rgb, depth, valid, height, slope, rough, lab, pmax, ent


