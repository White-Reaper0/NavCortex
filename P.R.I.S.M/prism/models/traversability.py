"""prism traversability: a learned off-road drivability / risk head.

What this stage answers
----------------------
A detector answers "what object is this?".  This stage answers "can *this vehicle*
drive here?" - which is a different question, because the answer depends on the
vehicle envelope in ``CFG.ugv`` (clearance, max step, width, max slope), not on the
object category.  The same patch of grass is SAFE for a 0.30 m-clearance platform and
OBSTACLE for the 0.045 m-clearance RC chassis this footage was shot from.

Supervision - read this before quoting any number
-------------------------------------------------
There is **no human traversability annotation** anywhere in this repo, and no
RELLIS-3D / GOOSE / ORFD ground truth is available offline.  The network is trained on
**geometric + semantic pseudo-labels** generated by
``prism/training/make_trav_labels.py`` from
  * metric height above the **local** ground surface, ground slope and roughness
    (``local_terrain_fields`` below, on top of ``perception/geometry.py``; scale
    anchored on the *assumed* camera height ``CFG.cam.height_above_ground_m``), and
  * the prism-7 terrain segmentation (itself distilled from an ADE20K teacher).
Every accuracy number reported for this stage is therefore **agreement with those
pseudo-labels**, never accuracy against ground truth.  Say it that way.

Why learn it at all, if the labels are rules?
---------------------------------------------
Three concrete reasons, all of which show up in the output videos:
  1. The rules need *clean* metric depth.  The network sees RGB as well, so it keeps
     producing a sane map where the depth fit degrades (dusk / low light clips).
  2. The rules are per-pixel and speckly; a conv decoder with an ImageNet trunk
     produces spatially coherent regions and interpolates across depth dropouts.
  3. Distilling into one small shared trunk gives one cheap forward pass that serves
     both traversability *and* uncertainty - which is what makes the CPU story real.

Architecture
------------
``SharedPerceptionTrunk``  MobileNetV3-Small (torchvision ImageNet weights, cached
locally) with an inflated 17-channel stem + a light top-down FPN to stride 4.
It is deliberately **shared** with ``models/uncertainty.py`` - one trunk, two thin
heads - because the contract asks for shared backbones for CPU efficiency.

Input stack (17 channels, at ``NET_W x NET_H`` = 320x180), documented exactly:
  0-2   RGB, ImageNet mean/std normalised.  **Absolute** normalisation, deliberately
        not per-frame contrast normalised, so a low-light frame stays dark and the
        uncertainty head can actually see the illumination it is meant to distrust.
  3     inverse depth      clip(0.5 / D_metres, 0, 1)        (0.5 m -> 1.0, 5 m -> 0.10)
  4     height above LOCAL ground  clip(h, -0.45, 0.90) / 0.90  (metres, + above grade)
  5     ground slope       clip(slope_deg, 0, 45) / 45
  6     roughness          clip(local height std, 0, 0.10) / 0.10   (metres)
  7     geometry valid     1 where metric depth + ground fit are usable
  8-14  prism-7 terrain one-hot (sky, trail, grass, rough_veg, obstacle, water, dynamic)
  15    segmentation max probability
  16    segmentation normalised entropy

Heads: 3x3 -> BN -> Hardswish -> two 1x1 convs, giving a 4-class logit map
(safe / risky / obstacle / unknown) and a 1-channel continuous risk regression.
"""
